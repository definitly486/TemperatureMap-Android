    private fun fetchChunk(chunk: List<City>): List<CityWeather> {
        val lats = chunk.joinToString(",") { it.lat.toString() }
        val lons = chunk.joinToString(",") { it.lon.toString() }
        val url = URL(
            "https://api.open-meteo.com/v1/forecast?latitude=$lats&longitude=$lons" +
                "&current=temperature_2m,apparent_temperature,relative_humidity_2m,weather_code,wind_speed_10m,precipitation,cloud_cover" +
                "&wind_speed_unit=ms"
        )
        val connection = (url.openConnection() as HttpURLConnection).apply {
            connectTimeout = 10000
            readTimeout = 15000
            requestMethod = "GET"
        }
        try {
            val code = connection.responseCode
            if (code != 200) {
                val err = connection.errorStream?.bufferedReader()?.use { it.readText() }
                if (code == 429) {
                    val retryAfter = parseRetryAfterMillis(connection.getHeaderField("Retry-After"))
                    throw RateLimitException(retryAfter, "HTTP 429 ${err.orEmpty().take(120)}")
                }
                throw RuntimeException("HTTP $code ${err.orEmpty().take(120)}")
            }
            val body = connection.inputStream.bufferedReader().use { it.readText() }
            // в чанке из одного города Open-Meteo возвращает объект, а не массив
            val arr = if (body.trimStart().startsWith("[")) JSONArray(body) else JSONArray().put(org.json.JSONObject(body))
            // порядок элементов ответа совпадает с порядком запрошенных координат
            return (0 until min(arr.length(), chunk.size)).map { i ->
                val cur = arr.getJSONObject(i).getJSONObject("current")
                CityWeather(
                    chunk[i],
                    cur.getDouble("temperature_2m"),
                    cur.getDouble("apparent_temperature"),
                    cur.getInt("relative_humidity_2m"),
                    cur.getDouble("wind_speed_10m"),
                    cur.optDouble("precipitation", 0.0),
                    cur.optInt("cloud_cover", 0),
                    cur.getInt("weather_code")
                )
            }
        } finally {
            connection.disconnect()
        }
    }

