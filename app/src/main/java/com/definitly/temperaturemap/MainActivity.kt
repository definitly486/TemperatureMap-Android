    private fun fetchWeatherForCities(cities: List<City>): List<CityWeather> {
        // NWS takes priority for US locations, including New York and other cities
        // that are also in the MET Norway city list.
        val nwsCities = cities.filter { it.name in nwsCityNames }
        val metCities = cities.filter { it.name in metNorwayCityNames && it.name !in nwsCityNames }
        val openMeteoCities = cities.filter { it.name !in nwsCityNames && it.name !in metNorwayCityNames }
        val result = ArrayList<CityWeather>(cities.size)

        openMeteoCities.chunked(100).forEach { result.addAll(fetchChunkWithRetry(it)) }

        nwsCities.forEach { city ->
            try {
                result.add(fetchNws(city))
            } catch (e: Exception) {
                android.util.Log.w("TemperatureMap", "NWS failed for ${city.name}; falling back to Open-Meteo", e)
                result.addAll(fetchChunkWithRetry(listOf(city)))
            }
        }

        // MET Norway's Locationforecast endpoint accepts one coordinate per request.
        metCities.forEachIndexed { index, city ->
            try {
                result.add(fetchMetNorwayWithRetry(city))
            } catch (e: Exception) {
                android.util.Log.w("TemperatureMap", "MET Norway failed for ${city.name}; falling back to Open-Meteo", e)
                result.addAll(fetchChunkWithRetry(listOf(city)))
            }
            if (index < metCities.lastIndex) Thread.sleep(1_000L)
        }
        return result
    }

    /** NWS gridpoint data is the authoritative US forecast source. */
    private fun fetchNws(city: City): CityWeather {
        val gridUrl = synchronized(nwsGridUrls) { nwsGridUrls[city.name] }
            ?: run {
                val pointsUrl = URL("https://api.weather.gov/points/${city.lat},${city.lon}")
                val pointsConnection = (pointsUrl.openConnection() as HttpURLConnection).apply {
                    connectTimeout = 10000
                    readTimeout = 15000
                    requestMethod = "GET"
                    setRequestProperty("User-Agent", "TemperatureMap-Android/1.0 (https://github.com/definitly486/TemperatureMap-Android.)")
                    setRequestProperty("Accept", "application/geo+json")
                }
                val discovered = try {
                    if (pointsConnection.responseCode != 200) throw IOException("NWS points HTTP ${pointsConnection.responseCode}")
                    org.json.JSONObject(pointsConnection.inputStream.bufferedReader().use { it.readText() })
                        .getJSONObject("properties").getString("forecastGridData")
                } finally {
                    pointsConnection.disconnect()
                }
                synchronized(nwsGridUrls) { nwsGridUrls[city.name] = discovered }
                discovered
            }

        val connection = (URL(gridUrl).openConnection() as HttpURLConnection).apply {
            connectTimeout = 10000
            readTimeout = 20000
            requestMethod = "GET"
            setRequestProperty("User-Agent", "TemperatureMap-Android/1.0 (https://github.com/definitly486/TemperatureMap-Android.)")
            setRequestProperty("Accept", "application/geo+json")
        }
        try {
            val code = connection.responseCode
            if (code != 200) {
                val err = connection.errorStream?.bufferedReader()?.use { it.readText() }
                if (code == 429) {
                    throw RateLimitException(parseRetryAfterMillis(connection.getHeaderField("Retry-After")), "NWS HTTP 429")
                }
                throw IOException("NWS HTTP $code ${err.orEmpty().take(120)}")
            }
            val props = org.json.JSONObject(connection.inputStream.bufferedReader().use { it.readText() })
                .getJSONObject("properties")

            fun firstValue(field: String): Double? {
                val values = props.optJSONObject(field)?.optJSONArray("values") ?: return null
                for (i in 0 until values.length()) {
                    val value = values.optJSONObject(i)?.opt("value")
                    if (value is Number) return value.toDouble()
                }
                return null
            }
            val tempC = firstValue("temperature") ?: throw IOException("NWS temperature unavailable")
            val windRaw = firstValue("windSpeed") ?: 0.0
            val windUnit = props.optJSONObject("windSpeed")?.optString("uom", "").orEmpty()
            val windMs = when {
                windUnit.contains("km_h") -> windRaw / 3.6
                windUnit.contains("mi_h") -> windRaw * 0.44704
                windUnit.contains("kn") -> windRaw * 0.514444
                else -> windRaw
            }
            val humidity = firstValue("relativeHumidity")?.roundToInt()?.coerceIn(0, 100) ?: 0
            val cloud = firstValue("skyCover")?.roundToInt()?.coerceIn(0, 100) ?: 0
            val precip = (firstValue("quantitativePrecipitation") ?: 0.0).coerceAtLeast(0.0)
            val weatherCode = when {
                precip >= 5.0 -> 65
                precip > 0.0 -> 61
                cloud >= 85 -> 3
                cloud >= 45 -> 2
                cloud >= 15 -> 1
                else -> 0
            }
            return CityWeather(city, tempC, tempC, humidity, windMs, precip, cloud, weatherCode)
        } finally {
            connection.disconnect()
        }
    }

    private fun fetchMetNorway(city: City): CityWeather {
        val url = URL(
            "https://api.met.no/weatherapi/locationforecast/2.0/compact" +
                "?lat=${"%.4f".format(Locale.US, city.lat)}&lon=${"%.4f".format(Locale.US, city.lon)}"
        )
        val connection = (url.openConnection() as HttpURLConnection).apply {
            connectTimeout = 10000
            readTimeout = 15000
            requestMethod = "GET"
            // MET Norway requires an identifiable, non-generic User-Agent.
            setRequestProperty("User-Agent", "TemperatureMap-Android/1.0 (https://github.com/definitly486/TemperatureMap-Android.)")
            setRequestProperty("Accept", "application/json")
        }
        try {
            val code = connection.responseCode
            if (code != 200) {
                val err = connection.errorStream?.bufferedReader()?.use { it.readText() }
                if (code == 429) {
                    val retryAfter = parseRetryAfterMillis(connection.getHeaderField("Retry-After"))
                    throw RateLimitException(retryAfter, "MET Norway HTTP 429 ${err.orEmpty().take(120)}")
                }
                throw IOException("MET Norway HTTP $code ${err.orEmpty().take(120)}")
            }

            val body = connection.inputStream.bufferedReader().use { it.readText() }
            val properties = org.json.JSONObject(body).getJSONObject("properties")
            val first = properties.getJSONArray("timeseries").getJSONObject(0)
            val data = first.getJSONObject("data")
            val details = data.getJSONObject("instant").getJSONObject("details")
            val next = data.optJSONObject("next_1_hours")
                ?: data.optJSONObject("next_6_hours")
            val precipitation = next?.optJSONObject("details")?.optDouble("precipitation_amount", 0.0) ?: 0.0
            val symbol = next?.optJSONObject("summary")?.optString("symbol_code", "").orEmpty()
            val temp = details.optDouble("air_temperature", 0.0)
            return CityWeather(
                city = city,
                temp = temp,
                feels = temp,
                humidity = details.optDouble("relative_humidity", 0.0).roundToInt(),
                wind = details.optDouble("wind_speed", 0.0),
                precipitation = precipitation,
                cloudCover = details.optDouble("cloud_area_fraction", 0.0).roundToInt(),
                code = metSymbolToWmoCode(symbol)
            )
        } finally {
            connection.disconnect()
        }
    }

    private fun metSymbolToWmoCode(symbol: String): Int {
        val normalized = symbol.substringBefore("_")
        return when {
            normalized.contains("thunder") -> 95
            normalized.contains("heavyrain") -> 65
            normalized.contains("rain") -> 61
            normalized.contains("sleet") -> 66
            normalized.contains("heavysnow") -> 75
            normalized.contains("snow") -> 71
            normalized.contains("fog") -> 45
            normalized.contains("partlycloudy") -> 2
            normalized.contains("cloudy") -> 3
            normalized.contains("fair") -> 1
            normalized.contains("clearsky") -> 0
            else -> 3
        }
    }

    private fun fetchMetNorwayWithRetry(city: City): CityWeather {
        var retry = 0
        var backoffMillis = 2_000L
        while (true) {
            try {
                return fetchMetNorway(city)
            } catch (e: RateLimitException) {
                if (retry >= max429Retries) throw e
                val delay = if (e.retryAfterMillis > 0L) e.retryAfterMillis else backoffMillis
                android.util.Log.w("TemperatureMap", "MET Norway HTTP 429; повтор через ${delay} мс")
                Thread.sleep(delay)
                retry++
                backoffMillis = (backoffMillis * 2).coerceAtMost(60_000L)
            }
        }
    }

    private fun parseRetryAfterMillis(value: String?): Long {
        if (value.isNullOrBlank()) return 0L
        value.trim().toLongOrNull()?.let { return (it * 1000L).coerceAtLeast(0L) }
        return try {
            val format = SimpleDateFormat("EEE, dd MMM yyyy HH:mm:ss z", Locale.US)
            ((format.parse(value.trim())?.time ?: 0L) - System.currentTimeMillis()).coerceAtLeast(0L)
        } catch (_: Exception) {
            0L
        }
    }

    private fun fetchChunkWithRetry(chunk: List<City>): List<CityWeather> {
        var retry = 0
        var backoffMillis = 1_000L
        while (true) {
            try {
                return fetchChunk(chunk)
            } catch (e: RateLimitException) {
                if (retry >= max429Retries) throw e
                val delay = if (e.retryAfterMillis > 0L) e.retryAfterMillis else backoffMillis
                android.util.Log.w("TemperatureMap", "HTTP 429; повтор через ${delay} мс (попытка ${retry + 1}/$max429Retries)")
                Thread.sleep(delay)
                retry++
                backoffMillis = (backoffMillis * 2).coerceAtMost(60_000L)
            }
        }
    }

    private fun scheduleViewportLoad() {
        viewportLoadRunnable?.let(handler::removeCallbacks)
        val task = Runnable { loadTemperatures() }
        viewportLoadRunnable = task
        handler.postDelayed(task, 250L)
    }

    /**
     * Пересчитывает число городов сразу, не ожидая завершения сетевых запросов.
     */
    private fun updateViewportStatus() {
        if (!::map.isInitialized || !::status.isInitialized || map.width <= 0 || map.height <= 0) return
        val count = visibleCities().size
        status.text = if (count == 0) {
            "В этой области нет городов · переместите карту или приблизьте её"
        } else {
            "Городов в текущей области: $count · обновление погоды…"
        }
    }

    private fun isCurrentViewport(requestedCities: List<City>): Boolean {
        if (!::map.isInitialized || map.width <= 0 || map.height <= 0) return false
        val currentNames = visibleCities().mapTo(HashSet()) { it.name }
        return currentNames == requestedCities.mapTo(HashSet()) { it.name }
    }

    /** Выбирает города текущего окна карты с учётом уровня приближения. */
    private fun visibleCities(): List<City> {
        if (!::map.isInitialized || map.width <= 0 || map.height <= 0) return CITIES.filter { it.tier == 1 }
        val bounds = map.boundingBox
        val zoom = map.zoomLevelDouble
        fun minZoom(tier: Int) = when (tier) {
            1 -> 3.0
            2 -> 4.5
            3 -> 5.5
            4 -> 6.5
            else -> 7.5
        }
        return CITIES.filter { city ->
            val inLongitude = if (bounds.lonWest <= bounds.lonEast) {
                city.lon >= bounds.lonWest && city.lon <= bounds.lonEast
            } else {
                city.lon >= bounds.lonWest || city.lon <= bounds.lonEast
            }
            zoom >= minZoom(city.tier) &&
                city.lat <= bounds.latNorth && city.lat >= bounds.latSouth && inLongitude
        }
    }

    private fun loadTemperatures() {
        val requestedCities = visibleCities()
        if (requestedCities.isEmpty()) {
            status.text = "Переместите карту к интересующему региону."
            return
        }

        val now = System.currentTimeMillis()
        val cached = synchronized(weatherCache) {
            requestedCities.mapNotNull { city ->
                weatherCache[city.name]?.takeIf { now - it.savedAt < cacheTtlFor(city) }?.weather
            }
        }
        val cachedNames = cached.mapTo(HashSet()) { it.city.name }
        val missing = requestedCities.filter { it.name !in cachedNames }

        // Сразу показываем свежие кэшированные данные, даже если часть городов ещё загружается.
        handler.post {
            val merged = synchronized(weatherCache) { weatherCache.values.map { it.weather } }
                .associateBy { it.city.name }.toMutableMap()
            cached.forEach { merged[it.city.name] = it }
            overlay.items = merged.values.toList()
            map.invalidate()
        }

        if (missing.isEmpty()) {
            if (isCurrentViewport(requestedCities)) {
                status.text = "Кэш актуален · городов в текущей области: ${requestedCities.size}"
            }
            return
        }
        if (!loading.compareAndSet(false, true)) {
            viewportReloadPending = true
            return
        }

        status.text = "Загружаем погоду из погодных источников для ${missing.size} видимых городов…"
        executor.execute {
            try {
                val result = fetchWeatherForCities(missing)
                val savedAt = System.currentTimeMillis()
                synchronized(weatherCache) {
                    result.forEach { weatherCache[it.city.name] = CachedWeather(it, savedAt) }
                }
                handler.post {
                    val merged = synchronized(weatherCache) { weatherCache.values.map { it.weather } }
                        .associateBy { it.city.name }
                    overlay.items = merged.values.toList()
                    overlay.selected = overlay.selected?.let { merged[it.city.name] }
                    map.invalidate()
                    if (isCurrentViewport(requestedCities)) {
                        status.text = "NWS + MET Norway + Open-Meteo · загружено: ${result.size} · городов в текущей области: ${requestedCities.size}"
                    }
                    loading.set(false)
                    if (viewportReloadPending) {
                        viewportReloadPending = false
                        scheduleViewportLoad()
                    }
                }
            } catch (e: Exception) {
                android.util.Log.e("TemperatureMap", "load failed", e)
                handler.post {
                    if (isCurrentViewport(requestedCities)) {
                        status.text = "Ошибка загрузки: ${e.javaClass.simpleName}: ${e.localizedMessage}"
                    }
                    loading.set(false)
                    if (viewportReloadPending) {
                        viewportReloadPending = false
                        scheduleViewportLoad()
                    }
                }
            }
        }
    }

    private fun showDetails(w: CityWeather) {
        status.text = "${w.city.name}: ${w.temp.roundToInt()}° (ощущается как ${w.feels.roundToInt()}°)\n" +
            "${weatherText(w.code)} · ветер ${w.wind.roundToInt()} м/с · осадки ${"%.1f".format(java.util.Locale.US, w.precipitation)} мм · облачность ${w.cloudCover}% · влажность ${w.humidity}%"
    }

    override fun onResume() {
        super.onResume()
        if (::map.isInitialized) map.onResume()
    }

    override fun onPause() {
        if (::map.isInitialized) map.onPause()
        super.onPause()
    }

    override fun onDestroy() {
        executor.shutdownNow()
        super.onDestroy()
    }

    inner class CityOverlay : Overlay() {
        var items: List<CityWeather> = emptyList()
        var selected: CityWeather? = null

        private val d = resources.displayMetrics.density
        private val fill = Paint(Paint.ANTI_ALIAS_FLAG)
        private val border = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            style = Paint.Style.STROKE
            color = Color.BLACK
            strokeWidth = 3f * d
        }
        private val tempPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.WHITE
            textSize = 14f * d
            textAlign = Paint.Align.CENTER
            isFakeBoldText = true
        }
        private val namePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(30, 30, 30)
            textSize = 11f * d
            textAlign = Paint.Align.CENTER
            isFakeBoldText = true
        }
        private val halo = Paint(namePaint).apply {
            color = Color.WHITE
            style = Paint.Style.STROKE
            strokeWidth = 3f * d
        }
        private val hits = ArrayList<Pair<CityWeather, RectF>>()

        private fun minZoom(tier: Int) = when (tier) {
            1 -> 3.0
            2 -> 4.5
            3 -> 5.5
            4 -> 6.5
            else -> 7.5
        }

        private fun metric(w: CityWeather): Double = when (layer) {
            WeatherLayer.TEMPERATURE -> w.temp
            WeatherLayer.PRECIPITATION -> w.precipitation
            WeatherLayer.WIND -> w.wind
            WeatherLayer.CLOUDS -> w.cloudCover.toDouble()
        }

        private fun colorFor(w: CityWeather): Int {
            val v = metric(w)
            return when (layer) {
                WeatherLayer.TEMPERATURE -> when {
                    v < -10 -> Color.rgb(35, 100, 220)
                    v < 0 -> Color.rgb(58, 160, 220)
                    v < 10 -> Color.rgb(60, 175, 120)
                    v < 20 -> Color.rgb(245, 175, 45)
                    else -> Color.rgb(225, 70, 55)
                }
                WeatherLayer.PRECIPITATION -> when {
                    v < 0.1 -> Color.rgb(180, 210, 230)
                    v < 1.0 -> Color.rgb(70, 180, 245)
                    v < 4.0 -> Color.rgb(25, 100, 230)
                    else -> Color.rgb(120, 55, 190)
                }
                WeatherLayer.WIND -> when {
                    v < 3 -> Color.rgb(80, 190, 120)
                    v < 7 -> Color.rgb(240, 210, 55)
                    v < 12 -> Color.rgb(245, 135, 40)
                    else -> Color.rgb(215, 55, 55)
                }
                WeatherLayer.CLOUDS -> when {
                    v < 20 -> Color.rgb(100, 190, 245)
                    v < 50 -> Color.rgb(120, 190, 160)
                    v < 80 -> Color.rgb(145, 145, 155)
                    else -> Color.rgb(70, 75, 90)
                }
            }
        }

        private fun labelFor(w: CityWeather): String = when (layer) {
            WeatherLayer.TEMPERATURE -> "${w.temp.roundToInt()}°"
            WeatherLayer.PRECIPITATION -> "${"%.1f".format(java.util.Locale.US, w.precipitation)}"
            WeatherLayer.WIND -> "${w.wind.roundToInt()} м/с"
            WeatherLayer.CLOUDS -> "${w.cloudCover}%"
        }

        override fun draw(canvas: Canvas, mapView: MapView, shadow: Boolean) {
            if (shadow) return
            hits.clear()
            val zoom = mapView.zoomLevelDouble
            val projection = mapView.projection
            val occupied = ArrayList<RectF>()
            val margin = 40f * d

            // Цветовые пятна показывают плавный визуальный переход между погодными точками.
            for (w in items) {
                val p = projection.toPixels(GeoPoint(w.city.lat, w.city.lon), null)
                val x = p.x.toFloat()
                val y = p.y.toFloat()
                if (x < -100f * d || y < -100f * d || x > mapView.width + 100f * d || y > mapView.height + 100f * d) continue
                val base = colorFor(w)
                fill.color = Color.argb(78, Color.red(base), Color.green(base), Color.blue(base))
                val radius = (18f + (zoom - 3f).toFloat().coerceIn(0f, 5f) * 5f) * d
                canvas.drawCircle(x, y, radius, fill)
            }

            val visible = items
                .filter { zoom >= minZoom(it.city.tier) || it === selected }
                .sortedBy { if (it === selected) 0 else it.city.tier }

            for (w in visible) {
                val p = projection.toPixels(GeoPoint(w.city.lat, w.city.lon), null)
                val x = p.x.toFloat()
                val y = p.y.toFloat()
                if (x < -margin || y < -margin || x > mapView.width + margin || y > mapView.height + margin) continue

                val label = labelFor(w)
                val pillW = tempPaint.measureText(label) + 14f * d
                val pillH = 26f * d
                val pill = RectF(x - pillW / 2, y - pillH / 2, x + pillW / 2, y + pillH / 2)
                val nameW = namePaint.measureText(w.city.name)
                val nameBaseline = pill.bottom + 12f * d
                val full = RectF(
                    min(pill.left, x - nameW / 2), pill.top,
                    max(pill.right, x + nameW / 2), nameBaseline + 4f * d
                )
                // метки не должны перекрываться: более важные города рисуются первыми
                if (w !== selected && occupied.any { RectF.intersects(it, full) }) continue
                occupied.add(full)
                hits.add(w to full)

                fill.color = colorFor(w)
                canvas.drawRoundRect(pill, 8f * d, 8f * d, fill)
                if (w === selected) canvas.drawRoundRect(pill, 8f * d, 8f * d, border)
                canvas.drawText(label, x, pill.centerY() + tempPaint.textSize * 0.35f, tempPaint)
                canvas.drawText(w.city.name, x, nameBaseline, halo)
                canvas.drawText(w.city.name, x, nameBaseline, namePaint)
            }
        }

        override fun onSingleTapConfirmed(e: MotionEvent, mapView: MapView): Boolean {
            val hit = hits.firstOrNull { it.second.contains(e.x, e.y) }?.first
            return if (hit != null) {
                selected = hit
                showDetails(hit)
                mapView.invalidate()
                startActivity(
                    Intent(this@MainActivity, DetailActivity::class.java)
                        .putExtra(DetailActivity.EXTRA_NAME, hit.city.name)
                        .putExtra(DetailActivity.EXTRA_LAT, hit.city.lat)
                        .putExtra(DetailActivity.EXTRA_LON, hit.city.lon)
                )
                true
            } else {
                false
            }
        }
    }
}
